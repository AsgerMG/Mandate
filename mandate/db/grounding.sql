-- Schema `grounding`: the one store of what every brain cites.
--
-- WHAT IT HOLDS. An original source file (bytes in the bucket `mandate-grounding`,
-- keyed by its sha256), the text extracted from it, the passages a brain cites,
-- and the embeddings those passages are searched by. Nothing a brain DERIVES
-- lives here (a classification, an enrichment, a gate, an actor): those stay in
-- the brain's own schema and point here by id.
--
-- WHY ONE SCHEMA FOR ALL BRAINS. A citation is only worth something if it names
-- a source and a date. Policy has always kept both; capital kept a laptop
-- filename. Two pipelines is how that happened, and each would have its own
-- duplicates (policy alone holds 72 duplicate versions, the same act ingested by
-- two adapters). One content-addressed store makes a duplicate impossible: the
-- same bytes are the same row, whoever fetched them.
--
-- APPEND-ONLY, enforced twice:
--   1. roles.sql grants every brain role SELECT + INSERT and nothing else.
--   2. the triggers below refuse UPDATE, DELETE and TRUNCATE for EVERY role,
--      the owner included, unless the session has said
--          SET grounding.allow_rewrite = 'on';
--      which only a reviewed migration does. A mistaken script run as the owner
--      therefore fails instead of rewriting what a published answer cited.
--   Correction = a NEW version (new bytes) or a NEW fetch row. A fact about a
--   source that changes (it was withdrawn, its URL moved) is a new row, never an
--   edit to an old one.
--
-- THE MODEL (one line each):
--   sources            who publishes; a registry, insert-only.
--   documents          one per canonical URL (or a urn: for a file with no URL).
--   document_versions  one per distinct BYTES (sha256 UNIQUE): the original in
--                      the bucket, its extracted text, who first saw it, when.
--   fetches            every observation "URL X served bytes Y at time T". This
--                      is what lets versions dedupe without losing a single fetch
--                      date: a re-fetch of unchanged bytes is a fetch row, not a
--                      version.
--   passages           a span of a version's text: the unit a brain cites.
--   passage_embeddings a passage's vector under ONE model. Separate from passages
--                      because append-only forbids filling a column in later, and
--                      because a model change must be a new row beside the old
--                      one, not an overwrite of it.
--
-- WHY halfvec. pgvector's halfvec stores 2 bytes a dimension instead of 4. On
-- policy.passages (125,263 vectors, 973 MB HNSW + ~500 MB of toasted vectors,
-- the database's biggest cost) that halves the vector storage. Retrieval quality
-- loss from fp16 on a normalised 1024-d embedding is below anything the brief
-- evals can resolve; Voyage itself serves int8 and binary.
--
-- Idempotent: safe to re-run. Run as the database admin; objects are owned by
-- grounding_owner (created in roles.sql, which must run first).

\set ON_ERROR_STOP on
BEGIN;

CREATE SCHEMA IF NOT EXISTS grounding AUTHORIZATION grounding_owner;
SET LOCAL ROLE grounding_owner;
SET LOCAL search_path = grounding, public;

CREATE TABLE IF NOT EXISTS grounding.sources (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key         TEXT NOT NULL UNIQUE CHECK (key ~ '^[a-z0-9][a-z0-9_.:-]*$'),
    name        TEXT NOT NULL,
    publisher   TEXT,
    base_url    TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by  TEXT NOT NULL DEFAULT current_user
);

CREATE TABLE IF NOT EXISTS grounding.documents (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- http(s) URL as canonicalised by mandate.grounding.canonical_url(), or a
    -- `urn:mandate:<brain>:<path>` for a file that never had a public URL (a
    -- register export a human downloaded, an index we parsed by hand).
    canonical_url  TEXT NOT NULL UNIQUE CHECK (canonical_url ~ '^(https?://|urn:)'),
    source_id      BIGINT REFERENCES grounding.sources(id),
    title          TEXT,
    publisher      TEXT,
    -- what the document IS, in the publisher's terms: 'regulation', 'call_document',
    -- 'award_register', 'scheme_page', 'state_aid_decision', ... Free text on
    -- purpose: a brain's controlled vocabulary lives in the brain.
    kind           TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by     TEXT NOT NULL DEFAULT current_user
);

CREATE TABLE IF NOT EXISTS grounding.document_versions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- the document these bytes were FIRST seen at. Every later sighting, at this
    -- or any other URL, is a row in grounding.fetches.
    document_id  BIGINT NOT NULL REFERENCES grounding.documents(id),
    fetched_at   TIMESTAMPTZ NOT NULL,
    sha256       TEXT NOT NULL UNIQUE CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    mime         TEXT NOT NULL,
    byte_size    BIGINT NOT NULL CHECK (byte_size >= 0),
    -- object key in the bucket: always sha256/<2 hex>/<sha256>, so the key is a
    -- function of the bytes and an upload is idempotent.
    bucket_key   TEXT NOT NULL UNIQUE CHECK (bucket_key = 'sha256/' || substr(sha256, 1, 2) || '/' || sha256),
    -- extracted text, NULL when nothing could be extracted (a scanned PDF).
    -- Passage spans index into THIS string.
    text         TEXT,
    extractor    TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by   TEXT NOT NULL DEFAULT current_user
);
CREATE INDEX IF NOT EXISTS ix_gdv_document ON grounding.document_versions(document_id);

CREATE TABLE IF NOT EXISTS grounding.fetches (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT NOT NULL REFERENCES grounding.documents(id),
    version_id   BIGINT NOT NULL REFERENCES grounding.document_versions(id),
    fetched_at   TIMESTAMPTZ NOT NULL,
    http_status  INTEGER,
    fetched_by   TEXT NOT NULL DEFAULT current_user,
    UNIQUE (document_id, version_id, fetched_at)
);
CREATE INDEX IF NOT EXISTS ix_gf_document_time ON grounding.fetches(document_id, fetched_at DESC);
CREATE INDEX IF NOT EXISTS ix_gf_version ON grounding.fetches(version_id);

CREATE TABLE IF NOT EXISTS grounding.passages (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id   BIGINT NOT NULL REFERENCES grounding.document_versions(id),
    -- which chunker cut it ('policy.chunking.v1', 'capital.gate_quote', ...).
    -- Two chunkers over one version are two passage sets, never a collision.
    chunker      TEXT NOT NULL,
    ordinal      INTEGER NOT NULL CHECK (ordinal >= 0),
    char_start   INTEGER NOT NULL CHECK (char_start >= 0),
    char_end     INTEGER NOT NULL,
    heading      TEXT,
    text         TEXT NOT NULL,
    token_count  INTEGER,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (char_end >= char_start),
    UNIQUE (version_id, chunker, ordinal)
);

CREATE TABLE IF NOT EXISTS grounding.passage_embeddings (
    passage_id  BIGINT NOT NULL REFERENCES grounding.passages(id),
    -- the model, as mandate.embedding names it. Never NULL: a vector without its
    -- model is a vector nobody can query correctly.
    model       TEXT NOT NULL,
    embedding   public.halfvec(1024) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (passage_id, model)
);
-- One HNSW index per model in use, partial, so a query names its model and can
-- never rank a vector from another space. mandate.embedding.MODEL is the only
-- model new rows are written in; a second index appears only during a planned
-- re-embed (see mandate/ops/one_model.sh).
CREATE INDEX IF NOT EXISTS ix_gpe_hnsw_voyage_4_large
    ON grounding.passage_embeddings USING hnsw (embedding public.halfvec_cosine_ops)
    WHERE model = 'voyage-4-large';

-- ── append-only, for every role ────────────────────────────────────────────
CREATE OR REPLACE FUNCTION grounding.refuse_rewrite() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF coalesce(current_setting('grounding.allow_rewrite', true), '') = 'on' THEN
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END IF;
  RAISE EXCEPTION 'grounding.% is append-only: % refused. A correction is a new row; '
                  'a reviewed migration sets grounding.allow_rewrite.', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'insufficient_privilege';
END $$;

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['sources','documents','document_versions','fetches','passages','passage_embeddings'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS append_only ON grounding.%I', t);
    EXECUTE format('CREATE TRIGGER append_only BEFORE UPDATE OR DELETE ON grounding.%I '
                   'FOR EACH ROW EXECUTE FUNCTION grounding.refuse_rewrite()', t);
    EXECUTE format('DROP TRIGGER IF EXISTS append_only_truncate ON grounding.%I', t);
    EXECUTE format('CREATE TRIGGER append_only_truncate BEFORE TRUNCATE ON grounding.%I '
                   'FOR EACH STATEMENT EXECUTE FUNCTION grounding.refuse_rewrite()', t);
  END LOOP;
END $$;

-- ── the views a brain reads ────────────────────────────────────────────────
-- The latest fetch of each document, and what it served. "Current" is derived,
-- never a flag someone has to remember to flip.
CREATE OR REPLACE VIEW grounding.current_versions AS
SELECT DISTINCT ON (f.document_id)
       f.document_id, f.version_id, f.fetched_at AS last_fetched_at
  FROM grounding.fetches f
 ORDER BY f.document_id, f.fetched_at DESC, f.id DESC;

COMMIT;
