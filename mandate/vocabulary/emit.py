"""Generate the shared vocabulary's two projections from vocabulary.json.

    python3 mandate/vocabulary/emit.py          # write both
    python3 mandate/vocabulary/emit.py --check  # exit 1 if either is stale

FREE: no network, no database. vocabulary.json is the SOURCE. This writes:

  mandate/vocabulary/generated.py            what both brains' Python imports
  web/lib/mandate/vocabulary.generated.ts    what the site imports

Why generated files rather than reading the JSON at runtime: the site's bundler
cannot reach outside web/, and a TS literal `as const` gives the compiler the
value union, so a typo in a sector id is a type error rather than a silent miss.
Why the check: a projection that must be regenerated by hand drifts the day
someone forgets, and when it drifts nothing fails (capital's vocabulary contract
found exactly that, three times). check.py runs this with --check in CI.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SOURCE = HERE / "vocabulary.json"
PY_OUT = HERE / "generated.py"
TS_OUT = ROOT / "web" / "lib" / "mandate" / "vocabulary.generated.ts"

HEADER = ("GENERATED by mandate/vocabulary/emit.py from mandate/vocabulary/vocabulary.json. "
          "Do not edit by hand: edit the JSON, then run `python3 mandate/vocabulary/emit.py`.")


def load() -> dict:
    return json.loads(SOURCE.read_text())


def _strip(o):
    """The projections carry values, not commentary: `_comment`/`_about` keys and
    the decisions' prose stay in the source, where they are read."""
    if isinstance(o, dict):
        return {k: _strip(v) for k, v in o.items() if not k.startswith("_")}
    if isinstance(o, list):
        return [_strip(v) for v in o]
    return o


def build_py(v: dict) -> str:
    data = _strip(v)
    data["decisions"] = [d["id"] for d in v["decisions"]]
    # A JSON literal parsed at import, not a pprint of a dict: pprint's layout
    # varies across Python versions, and the --check compares bytes.
    body = json.dumps(data, indent=1, ensure_ascii=False)
    assert "'''" not in body and "\\" not in body
    return (f'"""{HEADER}"""\n'
            "# ruff: noqa\n"
            "from __future__ import annotations\n\n"
            "import json as _json\n\n"
            f"VOCABULARY_VERSION = {json.dumps(v['version'])}\n\n"
            f"VOCABULARY: dict = _json.loads(r'''{body}''')\n")


def build_ts(v: dict) -> str:
    data = _strip(v)
    data["decisions"] = [d["id"] for d in v["decisions"]]
    body = json.dumps(data, indent=2, ensure_ascii=False)
    return (f"// {HEADER}\n"
            "// The prose behind every mapping is in the JSON's `decisions`; these are ids.\n\n"
            f"export const VOCABULARY_VERSION = {json.dumps(v['version'])};\n\n"
            f"export const VOCABULARY = {body} as const;\n")


def outputs() -> dict[Path, str]:
    v = load()
    return {PY_OUT: build_py(v), TS_OUT: build_ts(v)}


def stale() -> list[Path]:
    return [p for p, text in outputs().items()
            if not p.exists() or p.read_text() != text]


def main(argv: list[str]) -> int:
    if "--check" in argv:
        bad = stale()
        for p in bad:
            print(f"STALE: {p.relative_to(ROOT)} -- run python3 mandate/vocabulary/emit.py")
        return 1 if bad else 0
    for p, text in outputs().items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
