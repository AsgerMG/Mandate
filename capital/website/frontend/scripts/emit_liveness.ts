/**
 * Project the liveness rule to JSON so the Python ETL and its SQL read the SAME
 * definition the product uses, instead of four hand-copies.
 *
 * FREE. Writes data/liveness.json at the repo root.
 *
 * The rule used to live in five places at once — publishableInstruments(),
 * live_ids(), measure_country_class.ts, emit_peer_prior.py and
 * extend_recall_set.py — each under a "mirrors publishableInstruments()"
 * comment. It drifted, and when it drifted nothing failed: the ETL simply
 * withheld or proposed a different set of funds from the one the product shows.
 * That is the same fault emit_vocabulary.ts exists to stop, and this is the
 * same remedy.
 *
 * Run after ANY change to lib/intelligence/liveness.ts. check_liveness.ts fails
 * if the emitted file is stale, so this cannot be silently skipped.
 *
 * Run: npx tsx scripts/emit_liveness.ts
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { SCHEME_END_BASIS, closedSql } from "../lib/intelligence/liveness";

export const OUT = resolve(process.cwd(), "../../data/liveness.json");

export function build(): string {
  return JSON.stringify({
    _comment:
      "GENERATED by website/frontend/scripts/emit_liveness.ts from " +
      "lib/intelligence/liveness.ts. Do not edit by hand — regenerate. " +
      "Consumed by ETL/lib/liveness.py so every consumer of 'is this fund " +
      "still open' reads one definition rather than five that must be kept " +
      "in sync.",
    basis: SCHEME_END_BASIS,
    /** SQL for `this row is closed`, per dialect. Both are generated from the
     *  same function, so a change to the rule cannot reach one store only. */
    closedSql: {
      postgres: closedSql(),
      sqlite: closedSql({ sqlite: true }),
    },
  }, null, 2) + "\n";
}

if (process.argv[1]?.endsWith("emit_liveness.ts")) {
  writeFileSync(OUT, build());
  console.log(`wrote ${OUT}`);
}
