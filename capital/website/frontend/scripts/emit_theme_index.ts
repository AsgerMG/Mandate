// Generate the lexical theme index, so relevance.ts stops needing every
// instrument's gates at request time.
//
// ── Why this exists ────────────────────────────────────────────────────────
// buildIndex() in relevance.ts read gateFamily + requirement for EVERY
// instrument to build its TF-IDF index, and it runs on the production fast
// path (computeVerdict never computes semantic scores, so shortlist.ts always
// falls through to the lexical index). That single consumer forced the whole
// corpus's gates — 3.2 MB of a 4.45 MB phase one — into every request, to
// produce 0.24 MB of tokens.
//
// ── Why a TypeScript emitter and not a Python one ─────────────────────────
// The rules live in relevance.ts: THEMATIC_FAMILIES, ADMIN_NOISE, STOP and
// tokens(). Precomputing this in website/build/eligibility_export.py would
// copy all four across the language boundary, and this repo has been burned
// three times by cross-language "keep in sync" constants — most recently by a
// vocabulary that drifted and silently stopped gating.
//
// So the emitter imports relevance.ts's own themeTokensFor() and nothing else.
// A change to any of the four constants changes these bytes, and
// check_theme_index.ts fails the build.
//
// Same shape as emit_vocabulary.ts: exported OUT and build(), written only
// when invoked as main, so the checker can import build() without side
// effects.
//
// Run from website/frontend:  npx tsx scripts/emit_theme_index.ts
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { loadDbInstruments } from "../lib/intelligence/corpus";
import { themeTokensFor } from "../lib/intelligence/relevance";

export const OUT = resolve(process.cwd(), "lib/intelligence/themeIndex.generated.ts");

const HEADER = `// GENERATED by website/frontend/scripts/emit_theme_index.ts — do not edit.
// Regenerate with \`npx tsx scripts/emit_theme_index.ts\` from website/frontend;
// check_theme_index.ts fails the build when this and the corpus disagree.
//
// The tokens relevance.ts indexes each instrument under, derived from its name
// and its thematic gates. Committed because Vercel builds from the repo with
// no Python and no database, and generated because deriving it at request time
// is what made every request carry the whole corpus's gate text.
export const THEME_TOKENS: Record<string, string> = {
`;

export function build(): string {
  // Bare loadDbInstruments(), never hydrateDbInstruments(): the artifact must
  // be a pure function of the committed instrument_terms.json, or a byte-exact
  // check means nothing. This also applies resolveInheritedGates, which is
  // essential — 146 of 664 children carry no gates of their own and would
  // otherwise be indexed on their name alone.
  const rows = loadDbInstruments()
    .map((inst) => [inst.id, themeTokensFor(inst).join(" ")] as const)
    .filter(([, toks]) => toks.length > 0)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

  const body = rows
    .map(([id, toks]) => `  ${JSON.stringify(id)}: ${JSON.stringify(toks)},`)
    .join("\n");
  return `${HEADER}${body}\n};\n`;
}

if (process.argv[1]?.endsWith("emit_theme_index.ts")) {
  writeFileSync(OUT, build());
  const n = build().split("\n").length - 3;
  console.log(`wrote ${OUT} (${n} instruments)`);
}
