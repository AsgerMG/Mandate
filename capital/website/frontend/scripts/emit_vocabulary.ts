/**
 * Project the intake vocabulary to JSON so the Python ETL can read the SAME
 * definition the product uses, instead of a hand-copy.
 *
 * FREE. Writes data/vocabularies.json at the repo root.
 *
 * ETL/terms/encode_gates.py used to carry its own ENUM_VALUES and BAND_ORDERS
 * under a "Mirrors types.ts — keep in sync" comment. That comment is the whole
 * problem: a vocabulary that must be kept in sync by hand will drift, and when
 * it drifts nothing fails — the encoder simply emits values the product cannot
 * match, and rules quietly stop gating.
 *
 * Run after ANY change to the option lists in types.ts. check_vocabularies.ts
 * fails if the emitted file is stale, so this cannot be silently skipped.
 *
 * Run: npx tsx scripts/emit_vocabulary.ts
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { BAND_ORDERS, MULTI_VALUE_FIELDS, VOCABULARY } from "../lib/intelligence/vocabulary";
import { FIELD_REACH } from "../lib/intelligence/types";

export const OUT = resolve(process.cwd(), "../../data/vocabularies.json");

export function build(): string {
  const reach = Object.fromEntries(
    Object.entries(FIELD_REACH).map(([f, r]) => [f, r.via]),
  );
  return JSON.stringify({
    _comment:
      "GENERATED by website/frontend/scripts/emit_vocabulary.ts from " +
      "lib/intelligence/types.ts. Do not edit by hand — regenerate. " +
      "Consumed by ETL/terms/encode_gates.py so the encoder and the product " +
      "share one vocabulary rather than two that must be kept in sync.",
    enumValues: Object.fromEntries(
      Object.entries(VOCABULARY)
        .filter(([, v]) => v.values.length > 0)
        .map(([k, v]) => [k, v.values]),
    ),
    bandOrders: BAND_ORDERS,
    multiValueFields: [...MULTI_VALUE_FIELDS].sort(),
    // ── How each field gets answered, projected from FIELD_REACH ────────────
    // The ETL had THREE hand-copied lists of the intake fields — encode_gates
    // FIELDS, classify_gates_bulk INTAKE_FIELDS, extract_terms INTAKE_FIELDS —
    // and they had already drifted: two of the three still lacked sector,
    // exclusionFlags, activities and useOfFunds months after those were added.
    // A drifted list here does not throw; it just means the extractor is
    // hunting for the wrong things and the encoder is refusing the right ones.
    fieldReach: reach,
    // The fields an extractor may resolve a rule TO. 'none' is a first-class
    // answer — most gates that look like filters are decidable by nothing a
    // founder can tell us — and `unreachable` fields are excluded BY
    // CONSTRUCTION, so a model cannot key a rule to a question nobody is
    // asked. That is the whole property, enforced where the rule is written
    // rather than only where it is later read.
    encodableFields: [
      ...Object.entries(FIELD_REACH)
        .filter(([, r]) => r.via !== "unreachable")
        .map(([f]) => f)
        .sort(),
      "none",
    ],
  }, null, 2) + "\n";
}

if (process.argv[1]?.endsWith("emit_vocabulary.ts")) {
  writeFileSync(OUT, build());
  console.log(`wrote ${OUT}`);
}
