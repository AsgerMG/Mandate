// Typed interfaces for the JSON data files produced by website/build/*.py.

// synthesis.json — corpus-wide KPIs read by the home page and layout footer.
export interface Synthesis {
  companies: number;
  events: number;
  champions: number;
  stepCompanies: number;
  totalCapitalEur: string;
  totalCapitalEurRaw: number;
  countries: number;
  sourceFamilies: number;
  sectors: number;
}

// THE single source of truth for every corpus-wide figure shown on the site.
// Any page that states "X companies / Y events / €Z committed" MUST read it from
// here — never from investor_insights.json, companies_index.json, or a literal.
// synthesis.json is generated by website/build/synthesis.py from the one
// canonical SQL (compute_kpis); the build guardrail in build_site_data.py fails
// if any other generated file disagrees with it. This is why the home page,
// the footer, and /about-public-capital now always show the same number.
import synthesis from "@/public/data/synthesis.json";

export const corpusStats = synthesis as Synthesis;
