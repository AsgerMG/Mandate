// The quantities the site states in PROSE, derived rather than typed.
//
// ── The gap this closes ────────────────────────────────────────────────────
// `lib/data.ts` already made the KPI tiles follow the database: the company
// count, the euro total, the country count and the rest come from the ETL's own
// census at render time. What it did not cover is the other half of every page —
// the sentences. Those carried literals:
//
//   "…2020 to 2025"                        (home)   the corpus runs 2021–2025
//   "…2021 to 2025"                        (about)  the same claim, different
//                                                   number, on the same corpus
//   "two dozen national authorities"       (home)   the register covers 22
//   "Roughly three quarters … stay national" (home graph, ladder, about caption)
//                                                   three copies of one figure
//   "Only about a third … climbed there"   (ladder) restates conviction.pct,
//                                                   which is rendered live two
//                                                   sections later
//   "a third of its unselective portfolio" (about)  the Future Fund is 37.7%
//   "Top 12 countries by award count"      (about)  the chart's own row count
//   "146,911 companies in the funding record" (/brief) five thousand companies
//                                                   out of date, and contradicted
//                                                   by the footer of the very
//                                                   page it renders on
//
// Every one of those is a statement about the corpus that the corpus itself can
// make. A literal is not a shortcut for it; it is a claim that stops being true
// silently. `scripts/check_rendered_numbers.ts` now fails the build on the class,
// not on the list.
//
// ── Why here, and why from the artifacts ───────────────────────────────────
// This is deliberately NOT a second stats definition. The corpus-wide KPIs have
// exactly one definition (`website/build/lib/corpus_kpis.py`), carried to the
// site by the census and by synthesis.json, and nothing in this module
// recomputes any of them — a prose sentence that needs the company count reads
// `corpusStats()` like everything else.
//
// What lives here is the arithmetic that turns figures the BUILDERS already
// publish into the shape a sentence needs: a share, a window, a count of rows.
// Those figures come from `investor_insights.json` and `country_map.json`,
// committed artifacts regenerated by `build_site_data.py` from the same db, and
// already guarded — `check_consistency()` fails the build when a generated file
// disagrees with the canonical KPIs, and `check_corpus_census.ts` fails it when
// the committed artifacts drift from what the ETL holds. Deriving from them
// inherits both guards. Inventing a third path would have inherited neither.
//
// ── Server-side by convention, not by accident ─────────────────────────────
// Importing the two artifacts costs ~700 KB of bundle if it happens inside a
// "use client" module. It does not: the pages are server components, they call
// `corpusProse()` and hand the scalars down as props — the same shape
// `FundingLadder` already used for its rung ticket sizes. There is no fs and no
// pg here, so `check_client_boundary.ts` would not stop a client import; the
// payload budget would, which is the guard that should.

import insightsRaw from "@/public/data/investor_insights.json";
import countryMapRaw from "@/public/data/country_map.json";

/** The two channels that make an award NATIONAL rather than EU-level.
 *
 *  This is the site's own taxonomy, not a new one: the channels graph splits
 *  the machine into "the national road, on two rails" (state aid and the
 *  development banks) and "the European road" (everything pooled in Brussels).
 *  IPCEI sits on the European road there even though it is disbursed as
 *  national aid, and the home page says so in as many words, so it is counted
 *  European here too. Change the graph and change this together — they are one
 *  claim stated twice, once as a picture and once as a percentage. */
const NATIONAL_CHANNEL_IDS = ["state_aid_satr", "national_dev_banks"] as const;

/** The family key `country_map.py` writes for the State Aid Transparency
 *  Register. A country carrying it is a national authority whose aid awards we
 *  have loaded — which is exactly what "the register covers N authorities"
 *  means, so the count is the corpus's to make. */
const STATE_AID_FAMILY = "state_aid";

interface InsightsShape {
  stats: {
    conviction: { pct: number };
    futureFund: { asOf: string; positions: number; dead: number }[];
  };
  concentration: { id: string; events: number }[];
  countryMix: unknown[];
  rotation: { years: number[] };
}

interface CountryMapShape {
  countries: Record<string, { byFamily?: { family: string }[] }>;
}

const insights = insightsRaw as unknown as InsightsShape;
const countryMap = countryMapRaw as unknown as CountryMapShape;

export interface CorpusProse {
  /** First and last award year the corpus covers, and the window as a founder
   *  reads it. Two pages stated this window as two different ranges. */
  awardYearFrom: number;
  awardYearTo: number;
  awardWindow: string;
  /** Share of traced awards that stay on the national road, 0–100, one
   *  decimal dropped: the figure behind "roughly three quarters". */
  nationalAwardPct: number;
  /** How many national authorities' state-aid awards the corpus carries. */
  nationalAuthorities: number;
  /** Share of conviction-tier companies that arrived via smaller grants —
   *  the same `stats.conviction.pct` the /about Stat tile renders, so the
   *  prose and the tile cannot drift apart. */
  convictionClimbPct: number;
  /** The most recent Future Fund reading, and the dead share it implies. */
  futureFundAsOf: string;
  futureFundDeadPct: number;
  /** How many countries the country-mix chart actually plots. The caption used
   *  to name a number the chart no longer had to honour. */
  countryMixRows: number;
}

/** Round to whole percent for prose. Sentences do not carry decimals; the
 *  charts and the Stat tiles do, and they read the artifact directly. */
const pct = (n: number) => Math.round(n);

/**
 * Derive every prose quantity from the committed corpus artifacts.
 *
 * Pure and synchronous: these come from files that are part of the build, not
 * from Postgres, so there is nothing to await and nothing that can fail at
 * request time. The live/fallback distinction that `corpusStats()` carries does
 * not apply — an artifact is the only source these figures have ever had, and
 * `check_corpus_census.ts` is what notices when it drifts.
 */
export function corpusProse(): CorpusProse {
  const years = insights.rotation.years;
  const from = Math.min(...years);
  const to = Math.max(...years);

  const byId = new Map(insights.concentration.map((c) => [c.id, c.events]));
  const traced = insights.concentration.reduce((s, c) => s + c.events, 0);
  const national = NATIONAL_CHANNEL_IDS.reduce((s, id) => s + (byId.get(id) ?? 0), 0);

  const authorities = Object.values(countryMap.countries).filter((c) =>
    (c.byFamily ?? []).some((f) => f.family === STATE_AID_FAMILY)).length;

  const ff = insights.stats.futureFund[insights.stats.futureFund.length - 1];

  return {
    awardYearFrom: from,
    awardYearTo: to,
    awardWindow: `${from} to ${to}`,
    nationalAwardPct: traced > 0 ? pct((100 * national) / traced) : 0,
    nationalAuthorities: authorities,
    convictionClimbPct: insights.stats.conviction.pct,
    futureFundAsOf: ff.asOf,
    futureFundDeadPct: ff.positions > 0 ? pct((100 * ff.dead) / ff.positions) : 0,
    countryMixRows: insights.countryMix.length,
  };
}

