"""THE CENSUS, step 2d: the knowledge-map additions the census proposes, for the owner's review. No model.

    python3 capital/ETL/terms/census_map_diff.py

Reads capital/reference/census/<m>_network.csv (in-scope bodies against the map) and
shareholdings.csv. Every body not yet in the map becomes a proposed institution entry carrying
`register: <register>:<id>` (the loader cites the register page when the body has no org chart),
placed under its register parent when that parent is in the map or proposed, else under the
market's root. Writes capital/reference/census/map_additions.md: per market, a summary for the
owner and a ```yaml block that merge_audit_block.py merges.
"""
from __future__ import annotations

import csv
import json
import re
import unicodedata
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
REF = ROOT / "capital" / "reference" / "census"
MAP = ROOT / "mandate" / "brains" / "wincent" / "knowledge_map.yaml"
REGISTER = {"FR": "fr_annuaire", "UK": "uk_govuk_organisations", "IT": "it_indicepa", "EU": "eu_whoiswho"}
ROOTS = {"FR": ("fr.etat", "fr.regions"), "UK": ("uk.gov", "uk.devolved"), "IT": ("it.stato", "it.regioni"), "EU": ("eu.commission", "eu.commission")}
STOP = {"de", "du", "des", "la", "le", "les", "l", "d", "et", "pour", "the", "of", "and", "for", "di", "del", "della", "e", "per", "dei", "delle", "a"}


def ascii_(s: str) -> str:
    return unicodedata.normalize("NFKD", s or "").encode("ascii", "ignore").decode()


def norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", ascii_(s).lower()).strip()


def slug(name: str) -> str:
    ab = re.findall(r"\(([A-Za-z0-9&\-]{2,12})\)", name)
    if ab:
        return re.sub(r"[^a-z0-9]+", "_", ascii_(ab[-1]).lower()).strip("_")
    words = [w for w in norm(name).split() if w not in STOP]
    return "_".join(words[:4]) or "body"


def regional(name: str, market: str) -> bool:
    n = norm(name)
    return (market == "FR" and n.startswith(("region", "collectivite", "conseil regional"))) or \
           (market == "IT" and n.startswith(("regione", "provincia autonoma")))


def main() -> int:
    kmap = yaml.safe_load(MAP.read_text())["markets"]
    out = ["# Census: proposed knowledge-map additions (for the owner's review)", "",
           "Generated by capital/ETL/terms/census_map_diff.py from the official registers (scope judged in two passes) and the state shareholdings. "
           "Each entry cites its register entry; nothing here is written until the owner approves.", ""]
    totals = {}
    for m in ("FR", "IT", "UK", "EU"):
        net = list(csv.DictReader((REF / f"{m.lower()}_network.csv").open()))
        keys = {n["key"] for n in kmap[m]["institutions"]}
        by_name = {norm(n["name"]): n["key"] for n in kmap[m]["institutions"]}
        proposed: dict[str, dict] = {}
        name_to_key: dict[str, str] = {}
        for r in net:
            if r["in_map"]:
                continue
            k = f"{m.lower()}.{slug(r['name'])}"
            base, i = k, 2
            while k in keys or k in proposed:
                k, i = f"{base}_{i}", i + 1
            proposed[k] = r
            name_to_key[norm(r["name"])] = k
        entries = []
        for k, r in proposed.items():
            up = [p.strip() for p in (r["path_up"] or "").split(">") if p.strip()]
            parent = next((name_to_key.get(norm(p)) or by_name.get(norm(p)) for p in up
                           if name_to_key.get(norm(p)) or by_name.get(norm(p))), None)
            reg = regional(r["name"], m)
            parent = parent or (ROOTS[m][1] if reg else ROOTS[m][0])
            entries.append({"key": k, "name": r["name"], "kind": "ministry" if r["function"] == "budget_owner" and not reg else
                            ("regional_body" if reg else "institution"), "parent": parent, "level": "regional" if reg else "national",
                            "register": f"{REGISTER[m]}:{r['register_id']}", "role": r["function"]})
        share = [s for s in csv.DictReader((REF / "shareholdings.csv").open()) if s["market"] == m]
        share_new = [s for s in share if not any(norm(s["name"]).split()[0] in kn.split()[:2] for kn in by_name)]
        totals[m] = (len(net), len(net) - len(proposed), len(proposed), len(share), len(share_new))
        out += [f"## {m}", "",
                f"{len(net)} bodies in scope: {len(net) - len(proposed)} already in the map, **{len(proposed)} proposed**. "
                f"State shareholdings: {len(share)} listed, {len(share_new)} not yet in the map "
                f"({', '.join(s['name'] for s in share_new) or 'none'}; added with their own pages in step 4).", "",
                "| function | proposed |", "|---|---|"]
        fx: dict = {}
        for e in entries:
            fx[e["role"]] = fx.get(e["role"], 0) + 1
        out += [f"| {k} | {v} |" for k, v in sorted(fx.items(), key=lambda x: -x[1])] + ["", "```yaml", "institutions:"]
        out += ["  - {" + ", ".join(f"{f}: {json.dumps(e[f], ensure_ascii=False)}" for f in ("key", "name", "kind", "parent", "level", "register", "role")) + "}"
                for e in entries] + ["```", ""]
    (REF / "map_additions.md").write_text("\n".join(out) + "\n")
    for m, t in totals.items():
        print(f"{m}: {t[0]} in scope, {t[1]} in map, {t[2]} proposed; shareholdings {t[3]} ({t[4]} new)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
