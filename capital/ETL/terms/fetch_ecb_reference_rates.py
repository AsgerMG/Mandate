"""Pin the euro's exchange rates, with their date, into the corpus.

WHY THIS EXISTS
---------------
The intake's money scales are denominated in EURO. `TICKET_BANDS` is labelled
"EUR 100K - EUR 500K"; `turnoverBand` and `balanceBand` carry the euro
thresholds of the EU SME definition. A funder's rule, though, is written in the
funder's own currency: "up to 500 000 kroner", "150 tys. PLN", "minimum
20 000 000 Ft". Putting the second into the first is a conversion, and a
conversion needs a rate, a date and a source that a reader can check.

WHAT IT WRITES
--------------
`reference/fx_eur_reference_rates.json`, holding for every currency the ECB
publishes:

  spot      the most recent reference rate, with the date it was published
  min/max   the LOWEST and HIGHEST rate the currency has held against the euro
            over the declared window

The min/max is the point of the file. A band chosen at today's rate and read in
six months is a different verdict with no record of why -- unless the band is
the SAME at every rate the currency has actually held, in which case the
floating number is not load-bearing at all and the verdict is stable by
construction. `ETL/lib/fx_eur.py` implements that test and
`ETL/terms/check_gate_currency.py` enforces it.

THE SOURCE
----------
European Central Bank euro foreign exchange reference rates -- the rates the
ECB itself publishes each working day at 16:00 CET, free, no key, no licence
fee, and the reference the European Commission's own InforEuro series is built
on. Daily history back to 1999 in one 600 KB zip.

  https://www.ecb.europa.eu/stats/policy_and_exchange_rates/euro_reference_exchange_rates/

RATES ARE UNITS OF THE CURRENCY PER ONE EURO, which is the ECB's own convention
and the opposite of the one most people say out loud ("the pound is worth 1.17
euro"). The direction is asserted in the file and in fx_eur.py rather than left
to the reader, because inverting it silently is a factor-of-rate error in the
one place a factor-of-rate error is the whole defect.

  python3 ETL/terms/fetch_ecb_reference_rates.py [--window-years 10]
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import sys
import zipfile
from datetime import date, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "lib"))
from etl_env import ROOT  # noqa: E402

HIST_URL = "https://www.ecb.europa.eu/stats/eurofxref/eurofxref-hist.zip"
PAGE_URL = ("https://www.ecb.europa.eu/stats/policy_and_exchange_rates/"
            "euro_reference_exchange_rates/")
OUT = ROOT / "reference" / "fx_eur_reference_rates.json"


def fetch_history() -> list[dict[str, str]]:
    # `requests` rather than urllib: the system Python here has no CA bundle of
    # its own and urllib fails the ECB's certificate, while requests carries
    # certifi. Every other fetcher in ETL/ is on requests for the same reason.
    import requests
    blob = requests.get(HIST_URL, timeout=120).content
    with zipfile.ZipFile(io.BytesIO(blob)) as z:
        name = next(n for n in z.namelist() if n.endswith(".csv"))
        text = z.read(name).decode("utf-8")
    return list(csv.DictReader(io.StringIO(text)))


def build(window_years: int) -> dict:
    rows = fetch_history()
    if not rows:
        raise SystemExit("ECB history came back empty")
    # The file is newest-first. Take the spot date from the row that actually
    # carries the newest rate for each currency rather than from row 0: a
    # currency that has JOINED the euro (Bulgaria, 2026-01-01) stops being
    # quoted, and reading row 0 would report it as having no rate at all
    # instead of as having stopped floating on a knowable date.
    cutoff = (date.fromisoformat(rows[0]["Date"]) - timedelta(days=365 * window_years)).isoformat()
    currencies = [c for c in rows[0] if c and c != "Date"]
    out: dict[str, dict] = {}
    for c in currencies:
        obs = [(r["Date"], float(r[c])) for r in rows
               if r.get(c) and r[c].strip() not in ("", "N/A")]
        if not obs:
            continue
        window = [(d, v) for d, v in obs if d >= cutoff]
        if not window:
            continue
        out[c] = {
            "spot": window[0][1],
            "spot_date": window[0][0],
            "min": min(v for _, v in window),
            "max": max(v for _, v in window),
            "observations": len(window),
        }
    return {
        "_comment": (
            "GENERATED by ETL/terms/fetch_ecb_reference_rates.py. Do not edit by "
            "hand -- regenerate. RATES ARE UNITS OF THE CURRENCY PER ONE EURO "
            "(the ECB's own direction): GBP 0.856 means one euro buys 0.856 "
            "pounds. Read by ETL/lib/fx_eur.py and nothing else."),
        "source": "European Central Bank euro foreign exchange reference rates",
        "source_url": PAGE_URL,
        "data_url": HIST_URL,
        "direction": "units of currency per 1 EUR",
        "as_of": rows[0]["Date"],
        "window_start": cutoff,
        "window_years": window_years,
        "rates": dict(sorted(out.items())),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--window-years", type=int, default=10,
                    help="how far back the min/max envelope reaches")
    a = ap.parse_args()
    doc = build(a.window_years)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(doc, indent=1, sort_keys=False) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(doc['rates'])} currencies, "
          f"as of {doc['as_of']}, envelope from {doc['window_start']}")


if __name__ == "__main__":
    main()
