"""Regenerate ETL/schema/postgres_schema.sql from the live database.

The Postgres schema was not in source control at all: SQLite carried ten
numbered migrations while Postgres -- the database that actually serves the
product -- had none. Tables were created out of band and migrate_to_postgres.py
self-heals missing columns with ALTER TABLE ... ADD COLUMN IF NOT EXISTS, so
the schema only ever existed inside a running instance.

That is a single point of failure with no owner: production could not be
rebuilt from source, there was no review of schema changes, and no way to stand
up a staging environment provably identical to production.

This dumps the current shape into a committed file. It is a SNAPSHOT, not a
migration tool -- the honest next step is a real migration runner, but a
committed snapshot already removes the unrecoverable case. Run it after any
schema change; CI asserts the file exists.

Usage: python3 ETL/schema/dump_postgres_schema.py [--check]
       --check exits non-zero if the committed file is stale, for CI.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

import psycopg

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "ETL" / "schema" / "postgres_schema.sql"

HEADER = """-- Postgres schema for the live product database (Railway).
--
-- GENERATED by ETL/schema/dump_postgres_schema.py -- do not edit by hand.
--
-- Committed because it was not in source control at all: SQLite had ten
-- numbered migrations while Postgres, the database that actually serves the
-- product, had none. The concrete risk that closes: production could not be
-- rebuilt from source.
--
-- Regenerate with:  python3 ETL/schema/dump_postgres_schema.py
-- CI asserts this file exists; keep it current when the schema changes.
"""


def load_env() -> None:
    env = ROOT / ".env.local"
    if not env.exists():
        return
    for line in env.read_text().splitlines():
        if "=" in line and not line.startswith("#"):
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip().strip("\"'"))


def build() -> str:
    out = [HEADER]
    with psycopg.connect(os.environ["DATABASE_URL"]) as conn:
        tables = [r[0] for r in conn.execute(
            "SELECT tablename FROM pg_tables WHERE schemaname=current_schema() ORDER BY tablename")]
        for t in tables:
            cols = list(conn.execute(
                """SELECT column_name, data_type, is_nullable, column_default,
                          character_maximum_length
                     FROM information_schema.columns
                    WHERE table_schema = current_schema() AND table_name = %s
                    ORDER BY ordinal_position""", (t,)))
            out.append(f"\n-- {'─' * 3} {t} " + "─" * max(0, 58 - len(t)))
            out.append(f"CREATE TABLE IF NOT EXISTS {t} (")
            lines = []
            for name, dtype, nullable, default, maxlen in cols:
                ty = dtype.upper()
                if dtype == "character varying" and maxlen:
                    ty = f"VARCHAR({maxlen})"
                if dtype == "USER-DEFINED":
                    ty = "VECTOR"  # pgvector
                suffix = ""
                if default and "nextval" in str(default):
                    ty = "BIGSERIAL" if "big" in dtype else "SERIAL"
                elif default:
                    suffix = f" DEFAULT {default}"
                null = "" if nullable == "YES" else " NOT NULL"
                lines.append(f"  {name:26} {ty}{null}{suffix}")
            out.append(",\n".join(lines))
            out.append(");")
            for idx in conn.execute(
                    "SELECT schemaname, indexdef FROM pg_indexes WHERE schemaname=current_schema() "
                    "AND tablename=%s ORDER BY indexname", (t,)):
                # pg_indexes always schema-qualifies the table. The committed DDL
                # must not: it is applied by whichever role owns the brain, and the
                # role's search_path is what says where the brain lives.
                schema, idx = idx
                idx = idx.replace(f" ON {schema}.", " ON ")
                out.append(idx.replace("CREATE INDEX", "CREATE INDEX IF NOT EXISTS")
                              .replace("CREATE UNIQUE INDEX", "CREATE UNIQUE INDEX IF NOT EXISTS") + ";")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if the committed file is stale")
    args = ap.parse_args()
    load_env()
    if not os.environ.get("DATABASE_URL"):
        sys.exit("DATABASE_URL not set")

    current = build()
    if args.check:
        committed = OUT.read_text() if OUT.exists() else ""
        if committed != current:
            sys.exit(f"{OUT} is STALE — regenerate with "
                     f"`python3 ETL/schema/dump_postgres_schema.py`")
        print(f"{OUT.name} matches the live schema")
        return
    OUT.write_text(current)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
