"""ADEME ↔ SATR-FR overlap audit.

Both `ademe_aid` and the `satr_fr_*` sources live in public_funding_events and
both feed France totals. ADEME is a French granting authority, so its grants at
or above the EUR 100k State Aid Transparency Register threshold should ALSO be
published in SATR-FR (where France reports them under the parent ministry, not
under "ADEME"). This script measures how much of ADEME duplicates SATR-FR, so we
can document whether FR sums need de-duplication.

Match logic (conservative — we want to bound the *plausible* duplicate set):
  - Only ADEME rows >= EUR 100k can overlap (SATR omits below-threshold aid).
  - Candidate match = same normalised beneficiary name present in SATR-FR.
  - A candidate is counted as a *likely duplicate* when, additionally, some
    SATR-FR row for that beneficiary lands within +/-1 grant year AND within
    +/-15% on amount (ADEME's published figure can differ slightly from the
    SATR aid element).

Outputs project-mgmt/findings/ademe_satr_overlap.md and prints a one-line summary.
"""
from __future__ import annotations


# --- ETL path bootstrap (auto-added; see ETL/lib/etl_env.py) ---
import sys as _sys
from pathlib import Path as _Path
for _anc in _Path(__file__).resolve().parents:
    if (_anc / "lib" / "etl_env.py").exists():
        _sys.path.insert(0, str(_anc / "lib"))
        break
from etl_env import DB as _ETL_DB, ROOT as _ETL_ROOT  # noqa: E402,F401
# --- end ETL path bootstrap ---

import sqlite3
from collections import defaultdict
from pathlib import Path

# reuse the project's canonical name normaliser
import sys
pass  # sys.path handled by etl_env bootstrap
from satr_overlap_audit import normalise_name  # noqa: E402

DB_PATH = _ETL_DB
OUT_MD = _ETL_ROOT / "project-mgmt" / "findings" / "ademe_satr_overlap.md"

THRESHOLD = 100_000          # SATR general publication threshold
AMOUNT_TOL = 0.15            # +/-15% on amount
YEAR_WINDOW = 1              # +/-1 grant year


def grant_year(started: str | None, deadline: str | None) -> int | None:
    for d in (started, deadline):
        if d and len(d) >= 4 and d[:4].isdigit():
            return int(d[:4])
    return None


def main() -> None:
    conn = sqlite3.connect(DB_PATH)
    try:
        ademe = conn.execute(
            """
            SELECT c.canonical_name, c.raw_name, pfe.grant_amount_eur,
                   pfe.project_started, pfe.call_deadline
            FROM public_funding_events pfe JOIN companies c ON c.id = pfe.company_id
            WHERE pfe.source = 'ademe_aid'
            """
        ).fetchall()
        satr = conn.execute(
            """
            SELECT c.canonical_name, c.raw_name, pfe.grant_amount_eur,
                   pfe.project_started, pfe.call_deadline
            FROM public_funding_events pfe JOIN companies c ON c.id = pfe.company_id
            WHERE pfe.source LIKE 'satr_fr%'
            """
        ).fetchall()

        # Index SATR-FR by normalised name -> list of (amount, year)
        satr_by_name: dict[str, list[tuple[float | None, int | None]]] = defaultdict(list)
        for canon, raw, amt, started, deadline in satr:
            n = normalise_name(canon) or normalise_name(raw)
            if n:
                satr_by_name[n].append((amt, grant_year(started, deadline)))

        total = len(ademe)
        below = sum(1 for r in ademe if (r[2] or 0) < THRESHOLD)
        below_eur = sum(r[2] for r in ademe if (r[2] or 0) < THRESHOLD)

        eligible = [r for r in ademe if (r[2] or 0) >= THRESHOLD]
        eligible_eur = sum(r[2] for r in eligible)

        name_hit = 0          # >= threshold AND name found in SATR-FR
        name_hit_eur = 0.0
        likely_dup = 0        # name + year + amount corroborated
        likely_dup_eur = 0.0

        for canon, raw, amt, started, deadline in eligible:
            n = normalise_name(canon) or normalise_name(raw)
            cands = satr_by_name.get(n)
            if not cands:
                continue
            name_hit += 1
            name_hit_eur += amt or 0
            yr = grant_year(started, deadline)
            corroborated = False
            for s_amt, s_yr in cands:
                year_ok = (yr is None or s_yr is None or abs(s_yr - yr) <= YEAR_WINDOW)
                amt_ok = (
                    amt and s_amt and amt > 0
                    and abs(s_amt - amt) / amt <= AMOUNT_TOL
                )
                if year_ok and amt_ok:
                    corroborated = True
                    break
            if corroborated:
                likely_dup += 1
                likely_dup_eur += amt or 0

        def bn(x: float) -> str:
            return f"{x / 1e9:.2f}"

        lines = [
            "# ADEME ↔ SATR-FR overlap audit",
            "",
            "Generated by `ETL/events/load/qa/ademe_satr_overlap.py`. Both `ademe_aid` and "
            "`satr_fr_*` live in `public_funding_events` and both feed France "
            "totals, so any duplication inflates FR sums.",
            "",
            "## ADEME corpus",
            "",
            "| Metric | Rows | EUR bn |",
            "|---|---:|---:|",
            f"| ADEME total | {total:,} | {bn(sum(r[2] or 0 for r in ademe))} |",
            f"| Below SATR threshold (< €100k; cannot overlap) | {below:,} | {bn(below_eur)} |",
            f"| At/above threshold (≥ €100k; overlap-eligible) | {len(eligible):,} | {bn(eligible_eur)} |",
            "",
            "## Overlap with SATR-FR (eligible rows only)",
            "",
            "| Match strength | Rows | EUR bn | % of eligible € |",
            "|---|---:|---:|---:|",
            f"| Beneficiary name present in SATR-FR | {name_hit:,} | {bn(name_hit_eur)} | "
            f"{100 * name_hit_eur / eligible_eur:.1f}% |",
            f"| **Likely duplicate (name + year ±1 + amount ±15%)** | **{likely_dup:,}** | "
            f"**{bn(likely_dup_eur)}** | **{100 * likely_dup_eur / eligible_eur:.1f}%** |",
            "",
            "## Reading",
            "",
            f"Name-only overlap (€{bn(name_hit_eur)}bn) is an *upper bound* — large French "
            "beneficiaries (energy utilities, steelmakers) recur across many unrelated "
            "schemes, so a shared name is weak evidence. The corroborated set "
            f"(€{bn(likely_dup_eur)}bn, {100 * likely_dup_eur / eligible_eur:.1f}% of "
            "overlap-eligible ADEME euros) is the defensible duplication estimate.",
            "",
        ]
        OUT_MD.write_text("\n".join(lines), encoding="utf-8")
        print(f"ADEME total {total:,} rows / €{bn(sum(r[2] or 0 for r in ademe))}bn")
        print(f"  below threshold: {below:,} / €{bn(below_eur)}bn (no overlap possible)")
        print(f"  eligible ≥€100k: {len(eligible):,} / €{bn(eligible_eur)}bn")
        print(f"  name overlap:    {name_hit:,} / €{bn(name_hit_eur)}bn (upper bound)")
        print(f"  likely dup:      {likely_dup:,} / €{bn(likely_dup_eur)}bn "
              f"({100 * likely_dup_eur / eligible_eur:.1f}% of eligible €)")
        print(f"\nReport: {OUT_MD}")
    finally:
        conn.close()


if __name__ == "__main__":
    main()
