"""The instrument corpus, written down where git can hold it.

── What this is for ───────────────────────────────────────────────────────
The instrument half of the corpus — funds, their sources, their encoded
eligibility gates and clauses, and how you apply — is AUTHORED on a
workstation and lives in `data/db.sqlite`, which is gitignored because the
same file also carries 300k events and 645 MB. So the only copies of an
evening's gate encoding are: one laptop file, and whatever has since been
promoted to the corpus of record on the Railway volume.

On 2026-08-11 the census said the derived stores held **7,471** eligibility
gates and the corpus of record held **6,401**. 1,070 gates existed in exactly
one place, and the channels between the stores move the whole file with
`--overwrite`. There was no third copy and no way to make one.

This makes the third copy. It is text, it is committed, it diffs, and it
restores. It is NOT a backup of the database — it is a ledger of the rows a
human authored, which are the rows that cannot be regenerated by re-running
anything.

Events are deliberately NOT in here. There are 311k of them, they are of
record on the volume, and no derived store has ever been ahead on them. A
ledger that tried to hold them would be too big to review and would stop
being read, which is the failure mode this is guarding against.

── The three verbs ────────────────────────────────────────────────────────
  export    the store -> corpus-ledger/*.jsonl + MANIFEST.json
  verify    ledger vs a store; prints what each holds alone; exit 1 on drift
  restore   ledger -> a store, INSERT-ONLY. Never updates, never deletes.

`restore` is insert-only by design. A ledger is a record of what existed, not
an instruction about what should exist now; if a row has been edited in the
store since the export, the store's version is the newer fact and this must
not clobber it. To reconcile two live stores, use reconcile_stores.py.

── Usage ──────────────────────────────────────────────────────────────────
  python3 ETL/events/load/instrument_ledger.py export
  python3 ETL/events/load/instrument_ledger.py verify [--store PATH]
  python3 ETL/events/load/instrument_ledger.py restore --into PATH [--dry-run]
"""
from __future__ import annotations

# --- ETL path bootstrap (see ETL/lib/etl_env.py) ---
import sys as _sys
from pathlib import Path as _Path
for _anc in _Path(__file__).resolve().parents:
    if (_anc / "lib" / "etl_env.py").exists():
        _sys.path.insert(0, str(_anc / "lib"))
        break
from etl_env import DB, ROOT  # noqa: E402
# --- end ETL path bootstrap ---

import argparse  # noqa: E402
import hashlib  # noqa: E402
import json  # noqa: E402
import sqlite3  # noqa: E402
from datetime import datetime, timezone  # noqa: E402

_sys.path.insert(0, str(ROOT / "website" / "build" / "lib"))
from corpus_stores import FAMILIES  # noqa: E402
from reconcile_stores import IDENTITY, cols, has, key_of  # noqa: E402

LEDGER = ROOT / "corpus-ledger"

# The instrument family, in dependency order so a restore never inserts a
# child before its parent. Same table list as corpus_stores.FAMILIES
# ["instruments"] — asserted below rather than restated, because a second copy
# of that list is the defect this repository keeps paying for.
TABLES = [
    "funding_instruments",
    "funding_instrument_sources",
    "eligibility_gates",
    "eligibility_clauses",
    "instrument_application",
]
assert set(TABLES) == set(FAMILIES["instruments"]), (
    "instrument_ledger.TABLES has drifted from corpus_stores.FAMILIES['instruments']: "
    f"{sorted(set(TABLES) ^ set(FAMILIES['instruments']))}"
)

# Surrogate ids the target re-issues. Kept OUT of the ledger for every table
# whose identity is not the id itself: `eligibility_gates.id` is
# AUTOINCREMENT and is re-issued on every reload, so writing it down records a
# fact about one store's row numbering rather than about the gate. Where `id`
# IS the identity (funding_instruments, instrument_application) it is a stable
# text key and is carried.
def _drop_columns(table: str) -> set[str]:
    keys = IDENTITY.get(table) or []
    return set() if "id" in keys else {"id"}


def ro(path) -> sqlite3.Connection:
    con = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row
    return con


def rows_of(con: sqlite3.Connection, table: str) -> list[dict]:
    """Every row, as a dict, sorted by the table's declared identity.

    Sorted so the artefact is stable: a re-export with no change produces a
    byte-identical file and therefore an empty diff. An unsorted dump would
    show hundreds of moved lines on every run and nobody would read it.
    """
    keys = IDENTITY[table]
    drop = _drop_columns(table)
    keep = [c for c in cols(con, table) if c not in drop]
    out = [{c: r[c] for c in keep} for r in con.execute(f'SELECT * FROM "{table}"')]
    out.sort(key=lambda r: tuple("" if r.get(k) is None else str(r[k]) for k in keys))
    return out


def path_for(table: str) -> _Path:
    return LEDGER / f"{table}.jsonl"


def sha256_of(p: _Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def export(store) -> int:
    con = ro(store)
    LEDGER.mkdir(parents=True, exist_ok=True)
    # Relative to the checkout where it can be: an absolute path names one
    # laptop's home directory, which is noise in a diff and a fact about the
    # machine rather than about the corpus.
    p_store = _Path(store).resolve()
    try:
        shown = str(p_store.relative_to(ROOT))
    except ValueError:
        shown = p_store.name
    manifest = {
        "written_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "from_store": shown,
        "tables": {},
    }
    for t in TABLES:
        if not has(con, t):
            print(f"  {t:<30} absent from the store — skipped")
            continue
        rows = rows_of(con, t)
        p = path_for(t)
        with p.open("w", encoding="utf-8") as fh:
            for r in rows:
                fh.write(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n")
        manifest["tables"][t] = {
            "rows": len(rows),
            "identity": IDENTITY[t],
            "sha256": sha256_of(p),
            "bytes": p.stat().st_size,
        }
        print(f"  {t:<30} {len(rows):>7,} rows -> {p.relative_to(ROOT)}")
    (LEDGER / "MANIFEST.json").write_text(
        json.dumps(manifest, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    con.close()
    total = sum(v["rows"] for v in manifest["tables"].values())
    print(f"\n{total:,} rows written to {LEDGER.relative_to(ROOT)}/. Commit them.")
    return 0


def _ledger_rows(table: str) -> dict[tuple, dict]:
    p = path_for(table)
    if not p.exists():
        return {}
    keys = IDENTITY[table]
    out = {}
    for line in p.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        r = json.loads(line)
        out[tuple("" if r.get(k) is None else str(r[k]) for k in keys)] = r
    return out


def verify(store) -> int:
    """What the ledger and a store hold that the other does not. Reads only."""
    con = ro(store)
    print(f"ledger  {LEDGER}\nstore   {store}\n")
    drift = 0
    for t in TABLES:
        led = _ledger_rows(t)
        if not has(con, t):
            print(f"  {t:<30} ledger {len(led):>7,}   store: TABLE ABSENT")
            drift += len(led)
            continue
        keys = IDENTITY[t]
        cur = {key_of(r, keys): r for r in con.execute(f'SELECT * FROM "{t}"')}
        only_ledger = set(led) - set(cur)
        only_store = set(cur) - set(led)
        drift += len(only_ledger) + len(only_store)
        flag = "" if not (only_ledger or only_store) else "   <-- drift"
        print(f"  {t:<30} ledger {len(led):>7,}   store {len(cur):>7,}   "
              f"only-ledger {len(only_ledger):>6,}  only-store {len(only_store):>6,}{flag}")
        for k in list(only_store)[:5]:
            print(f"      store only: {k}")
    con.close()
    if drift:
        print(f"\n{drift:,} row(s) differ. Re-export if the store is the newer truth:\n"
              f"  python3 ETL/events/load/instrument_ledger.py export")
        return 1
    print("\nledger and store agree.")
    return 0


def restore(target, dry: bool) -> int:
    """Put back rows the target does not have. INSERT-only; nothing is updated
    and nothing is deleted, so running this against a healthy store is a no-op
    and running it against a store that lost the ledger's rows brings them back.
    """
    tgt = sqlite3.connect(target)
    tgt.row_factory = sqlite3.Row
    print(f"into {target}" + ("   (DRY RUN)" if dry else "") + "\n")
    total = 0
    for t in TABLES:
        led = _ledger_rows(t)
        if not led:
            print(f"  {t:<30} nothing in the ledger")
            continue
        if not has(tgt, t):
            print(f"  {t:<30} SKIPPED — table absent from the target (run migrations)")
            continue
        keys = IDENTITY[t]
        tcols = set(cols(tgt, t))
        cur = {key_of(r, keys) for r in tgt.execute(f'SELECT * FROM "{t}"')}
        new = [led[k] for k in sorted(led) if k not in cur]
        missing_cols = sorted({c for r in new for c in r} - tcols)
        writable = [c for c in (new[0] if new else {}) if c in tcols]
        if new and not dry:
            ph = ", ".join("?" * len(writable))
            tgt.executemany(
                f'INSERT INTO "{t}" ({", ".join(writable)}) VALUES ({ph})',
                [tuple(r.get(c) for c in writable) for r in new])
        total += len(new)
        print(f"  {t:<30} +{len(new):,} restored, {len(cur):,} already present")
        if missing_cols:
            print(f"      columns the target has no room for (run migrations "
                  f"first, these values are NOT restored): {missing_cols}")
    if dry:
        tgt.rollback()
        print("\nDRY RUN — nothing written.")
    else:
        tgt.commit()
        print(f"\n{total:,} row(s) restored. Nothing was updated and nothing deleted.")
    tgt.close()
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("verb", choices=["export", "verify", "restore"])
    ap.add_argument("--store", default=str(DB),
                    help="the store to export from / verify against (default: the local corpus)")
    ap.add_argument("--into", help="the store to restore INTO (required for restore)")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    if args.verb == "export":
        return export(args.store)
    if args.verb == "verify":
        return verify(args.store)
    if not args.into:
        ap.error("restore needs --into <store.sqlite>")
    return restore(args.into, args.dry_run)


if __name__ == "__main__":
    raise SystemExit(main())
