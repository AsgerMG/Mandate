// The degraded brief, rendered so the suppression notice can be LOOKED at.
//
// The degradation policy withholds funds whose openness cannot be confirmed
// and tells the founder how many are missing (lib/intelligence/liveness.ts,
// `withheldNotice`). That sentence sits above the first row of the table a
// founder acts on, and it shipped compiling, type-checking and unit-tested
// with nobody having seen it on a page. Wording that reads as an apology, or
// as a hedge over the rows below it, is a defect this product cannot detect in
// a terminal.
//
// Nothing here is fabricated:
//
//   * the brief is the same recorded fixture `/brief/preview` renders;
//   * the sentence is not written here — it comes from `withheldNotice()`, the
//     product's own function, so what is on screen is what a founder gets;
//   * the counts are the ones a real degraded request produces. Measured
//     2026-08-07 against the committed snapshot with Postgres unreachable, 5
//     rows are withheld corpus-wide and a founder is told only what left THEIR
//     table: 5 for the two archetypes that draw on the Spanish convocatoria
//     register, 0 for the other ten. 1 is included because it is the only count
//     that changes the sentence's grammar, and singular text is where this kind
//     of string breaks.
//
//     They were 73 and 7 until the rule was made precise. That is the point of
//     keeping this page honest about where its numbers come from: it moves when
//     the policy moves, and a page carrying invented counts would have gone on
//     showing a paragraph no founder would ever see.
//
// Never reachable in production — see notFound() below.
import { notFound } from "next/navigation";
import { InstitutionsTable, Memo } from "@/lib/intelligence/panelReport";
import { withheldNotice } from "@/lib/intelligence/corpus";
import fixture from "@/lib/intelligence/__fixtures/report.json";
import type { IntelligenceReport } from "@/lib/intelligence/types";
import { corpusProse } from "@/lib/corpusProse";

export const metadata = { title: "Withheld notice preview" };

/** The counts a real degraded request produces, plus the singular boundary. */
const COUNTS = [5, 1] as const;

export default function WithheldPreviewPage() {
  if (process.env.NODE_ENV === "production") notFound();
  const report = fixture as unknown as IntelligenceReport;
  return (
    <main className="wrap py-10">
      <p className="mb-1 font-mono text-[11px] uppercase tracking-[0.14em] text-[var(--accent)]">
        Degraded path · what the founder is told
      </p>
      <h1 className="mb-2 text-2xl font-semibold">
        The table, with funds withheld
      </h1>
      <p className="mb-10 max-w-2xl text-[15px] text-[var(--muted-foreground)]">
        The same brief at the counts a degraded request actually produces, plus
        the singular boundary. Only the sentence above the table changes; the
        rows below it are the rows that survived. The sentence is generated by
        the product, not written into this page.
      </p>
      {/* The STREAMED preview first, because it is the surface a founder looks
          at longest: it is on screen for the two to three minutes the writer
          takes, which is ample time to count the rows and conclude that is the
          answer. Same component as the finished brief, so the notice has to
          sit correctly above skeleton rows as well as real ones. */}
      <section className="mb-16">
        <p className="mb-3 font-mono text-[11px] uppercase tracking-[0.14em] text-[var(--muted-foreground)]">
          Streamed preview, 5 withheld
        </p>
        <div className="border border-[var(--border)] bg-[var(--paper)] px-5 py-5 sm:px-7 sm:py-6 text-[15px] leading-relaxed text-[var(--foreground)]"
          style={{ fontFamily: "var(--font-newsreader), Georgia, serif" }}>
          <InstitutionsTable
            institutions={report.institutions}
            withheld={withheldNotice(5)}
            pending
          />
        </div>
      </section>
      {COUNTS.map((count) => (
        <section key={count} className="mb-16">
          <p className="mb-3 font-mono text-[11px] uppercase tracking-[0.14em] text-[var(--muted-foreground)]">
            Finished brief, {count} withheld
          </p>
          <Memo report={{ ...report, withheld: withheldNotice(count) }} corpusWindow={corpusProse().awardWindow} />
        </section>
      ))}
    </main>
  );
}
