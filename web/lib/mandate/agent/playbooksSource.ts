/**
 * Read mandate/playbooks/*.md into the shape the runtime ships. Used by the
 * generator (scripts/emit_playbooks.ts) and by the drift test, never at
 * request time: on Vercel the site's root is web/, and a file outside it is not
 * guaranteed to be in the deployment. So the playbooks ship as a generated
 * module, and the test fails when that module and these files differ.
 */
import { readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";

export const PLAYBOOK_DIR = resolve(__dirname, "../../../../mandate/playbooks");
/** Persona and method files; every other .md (bar README) is a job playbook. */
export const CORE = ["method", "wincent", "regina"] as const;

export type { PlaybookBundle } from "./playbookTypes";
import type { PlaybookBundle } from "./playbookTypes";

export function readPlaybooks(dir = PLAYBOOK_DIR): PlaybookBundle {
  const files = readdirSync(dir).filter((f) => f.endsWith(".md") && f !== "README.md").sort();
  const core = {} as PlaybookBundle["core"];
  const jobs: PlaybookBundle["jobs"] = {};
  for (const f of files) {
    const name = f.replace(/\.md$/, "");
    const text = readFileSync(join(dir, f), "utf8");
    if ((CORE as readonly string[]).includes(name)) {
      core[name as (typeof CORE)[number]] = text;
    } else {
      const title = (text.split("\n")[0] ?? name).replace(/^#\s*/, "").trim();
      jobs[name] = { title, text };
    }
  }
  for (const c of CORE) if (!core[c]) throw new Error(`mandate/playbooks/${c}.md is missing`);
  return { core, jobs };
}

export function renderGenerated(bundle: PlaybookBundle): string {
  return [
    "// GENERATED by scripts/emit_playbooks.ts from mandate/playbooks/*.md. Do not edit:",
    "// edit the markdown and re-run `npx tsx scripts/emit_playbooks.ts` (from web/).",
    "// lib/mandate/agent/playbooks.test.ts fails when this file is stale.",
    "/* eslint-disable */",
    'import type { PlaybookBundle } from "./playbookTypes";',
    "",
    `export const PLAYBOOKS: PlaybookBundle = ${JSON.stringify(bundle, null, 2)};`,
    "",
  ].join("\n");
}
