/**
 * Project the offer-route rule to JSON so the Python ETL and its SQL read the
 * SAME definition the product uses.
 *
 * FREE. Writes data/offer_route.json at the repo root.
 *
 * Same remedy as emit_liveness.ts and emit_vocabulary.ts, adopted at birth
 * rather than after the drift: the last judgement of this kind
 * (`closed_beneficiary_list`) shipped with the constant added to the Python and
 * the row-wise Python predicate never taught about it, so the two languages
 * disagreed from the first commit and nothing failed.
 *
 * Run after ANY change to lib/intelligence/offerRoute.ts.
 * check_offer_route.ts fails if this file is stale.
 *
 * Run: npx tsx scripts/emit_offer_route.ts
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { ROUTE_STATUS, hasOfferRouteSql } from "../lib/intelligence/offerRoute";

export const OUT = resolve(process.cwd(), "../../data/offer_route.json");

export function build(): string {
  return JSON.stringify({
    _comment:
      "GENERATED by website/frontend/scripts/emit_offer_route.ts from " +
      "lib/intelligence/offerRoute.ts. Do not edit by hand — regenerate. " +
      "Consumed by ETL/lib/offer_route.py so 'can a founder apply to this' " +
      "has one definition rather than one per consumer.",
    status: ROUTE_STATUS,
    hasRouteSql: { postgres: hasOfferRouteSql(), sqlite: hasOfferRouteSql() },
  }, null, 2) + "\n";
}

if (process.argv[1]?.endsWith("emit_offer_route.ts")) {
  writeFileSync(OUT, build());
  console.log(`wrote ${OUT}`);
}
